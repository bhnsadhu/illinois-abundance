import { PGlite } from '@electric-sql/pglite';
import { afterAll, afterEach, beforeAll, beforeEach, describe, expect, it, vi } from 'vitest';
import { createDatabase } from '@/lib/database/client';
import { publicDatabase } from '@/lib/database/public';
import { serviceDatabase } from '@/lib/database/service';

const mocks = vi.hoisted(() => ({ neon: vi.fn() }));
vi.mock('@neondatabase/serverless', () => ({ neon: mocks.neon }));

type Row = Record<string, unknown>;
type Result = { rows: Row[]; rowCount: number };
type Statement = { text: string; values: unknown[]; transaction: boolean };
type TransactionOptions = { readOnly?: boolean; isolationLevel?: string; fetchOptions?: { cache?: string }; fullResults?: boolean };
let db: PGlite;
let statements: Statement[];
let transactions: TransactionOptions[];

// Replace only Neon's HTTP transport. Generated SQL, RLS, privileges, conflicts,
// bound values and transaction-local roles are executed by real PostgreSQL.
class TransportQuery implements PromiseLike<Result> {
  constructor(readonly text: string, readonly values: unknown[] = []) {}
  then<T = Result, E = never>(resolve?: ((value: Result) => T | PromiseLike<T>) | null, reject?: ((reason: unknown) => E | PromiseLike<E>) | null): PromiseLike<T | E> {
    statements.push({ text: this.text, values: this.values, transaction: false });
    return db.query<Row>(this.text, this.values).then(result => ({ rows: result.rows, rowCount: result.affectedRows || result.rows.length })).then(resolve, reject);
  }
}

function transport() {
  const query = (text: string, values?: unknown[]) => new TransportQuery(text, values);
  return {
    query,
    async transaction(work: (transaction: { query: typeof query }) => TransportQuery[], options: TransactionOptions) {
      transactions.push(options);
      const queries = work({ query });
      return db.transaction(async transaction => {
        if (options.isolationLevel === 'RepeatableRead') await transaction.exec('SET TRANSACTION ISOLATION LEVEL REPEATABLE READ');
        if (options.readOnly) await transaction.exec('SET TRANSACTION READ ONLY');
        const results: Result[] = [];
        for (const statement of queries) {
          statements.push({ text: statement.text, values: statement.values, transaction: true });
          const result = await transaction.query<Row>(statement.text, statement.values);
          results.push({ rows: result.rows, rowCount: result.affectedRows || result.rows.length });
        }
        return results;
      });
    },
  };
}

beforeAll(async () => {
  db = new PGlite();
  await db.exec(`
    CREATE ROLE anon;
    GRANT USAGE ON SCHEMA public TO anon;
    CREATE TABLE posts (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      title text NOT NULL UNIQUE,
      score integer NOT NULL DEFAULT 0,
      is_published boolean NOT NULL DEFAULT false,
      note text,
      sources jsonb NOT NULL DEFAULT '[]',
      created_at timestamptz NOT NULL DEFAULT '2026-10-12T12:00:00Z',
      author_email text NOT NULL DEFAULT 'private@illinois.edu'
    );
    ALTER TABLE posts ENABLE ROW LEVEL SECURITY;
    GRANT SELECT (id,title,score,is_published,note,sources,created_at) ON posts TO anon;
    CREATE POLICY published_only ON posts FOR SELECT TO anon USING (is_published);
    CREATE VIEW public_posts WITH (security_invoker = true, security_barrier = true) AS
      SELECT id,title,score,is_published,note,sources,created_at FROM posts;
    GRANT SELECT ON public_posts TO anon;
    CREATE VIEW public_unapproved AS SELECT author_email FROM posts;
    CREATE FUNCTION echo_arguments(p_text text, p_payload jsonb) RETURNS jsonb LANGUAGE sql AS
      $$ SELECT jsonb_build_object('text', p_text, 'payload', p_payload) $$;
    CREATE FUNCTION echo_boolean(p_value boolean) RETURNS boolean LANGUAGE sql AS $$ SELECT p_value $$;
  `);
}, 30000);

beforeEach(async () => {
  await db.exec(`
    TRUNCATE posts RESTART IDENTITY;
    INSERT INTO posts (title,score,is_published,note) VALUES
      ('Published one', 10, true, null),
      ('Draft', 20, false, 'private note'),
      ('Published three', 30, true, 'third'),
      ('Published four', 30, true, null);
  `);
  statements = [];
  transactions = [];
  mocks.neon.mockReset().mockImplementation(transport);
  vi.stubEnv('DATABASE_URL', 'postgresql://test:secret@test.neon.tech/test');
});

afterEach(() => { vi.unstubAllEnvs(); });
afterAll(async () => { await db.close(); });

describe('Neon adapter query semantics', () => {
  it('binds text values without interpreting SQL or changing database content', async () => {
    const attack = "x'); DROP TABLE posts; --";
    const inserted = await serviceDatabase().from('posts').insert({ title: attack, is_published: true }).select('id,title').single();
    expect(inserted.error).toBeNull();
    expect(inserted.data?.title).toBe(attack);
    const selected = await serviceDatabase().from('posts').select('title').eq('title', attack).single();
    expect(selected.data).toEqual({ title: attack });
    expect(statements.every(statement => !statement.text.includes(attack))).toBe(true);
    expect(statements.at(-1)?.values).toEqual([attack]);
    expect((await db.query('SELECT COUNT(*)::int AS total FROM posts')).rows[0]).toEqual({ total: 5 });
  });

  it('orders stably, applies inclusive ranges, and counts all matches beyond the page', async () => {
    const result = await serviceDatabase().from('posts').select('id,title', { count: 'exact' })
      .is('is_published', true).order('score', { ascending: false }).order('id', { ascending: false }).range(1, 2);
    expect(result.error).toBeNull();
    expect(result.data).toEqual([{ id: 3, title: 'Published three' }, { id: 1, title: 'Published one' }]);
    expect(result.count).toBe(3);
    expect(transactions).toHaveLength(1);
    expect(transactions[0]).toMatchObject({ readOnly: true, isolationLevel: 'RepeatableRead' });
    const empty = await serviceDatabase().from('posts').select('id', { count: 'exact' }).range(99, 100);
    expect(empty).toEqual({ data: [], error: null, count: 4 });
  });

  it('supports count-only requests without fetching private row values', async () => {
    const result = await serviceDatabase().from('posts').select('author_email', { count: 'exact', head: true }).eq('is_published', false);
    expect(result).toEqual({ data: null, error: null, count: 1 });
    expect(statements).toHaveLength(1);
    expect(statements[0].text).toContain('COUNT(*)');
    expect(statements[0].text).not.toContain('author_email');
  });

  it('combines all comparison filters, scalar IN values and explicit NULL semantics', async () => {
    const result = await serviceDatabase().from('posts').select('id').neq('id', 1).gte('score', 20).lte('score', 30)
      .gt('score', 10).lt('score', 40).in('id', [2, 3, 4]).is('note', null).is('is_published', true);
    expect(result).toEqual({ data: [{ id: 4 }], error: null, count: null });
    expect((await serviceDatabase().from('posts').select('id').in('id', [])).data).toEqual([]);
    expect((await serviceDatabase().from('posts').select('id').is('is_published', false)).data).toEqual([{ id: 2 }]);
  });

  it('supports zero limits and explicit null ordering', async () => {
    expect((await serviceDatabase().from('posts').select('id').limit(0)).data).toEqual([]);
    const result = await serviceDatabase().from('posts').select('id').order('note', { nullsFirst: true }).order('id').limit(2);
    expect(result.data).toEqual([{ id: 1 }, { id: 4 }]);
  });

  it('distinguishes missing and nonunique single rows', async () => {
    expect(await serviceDatabase().from('posts').select('id').eq('id', 1).single()).toEqual({ data: { id: 1 }, error: null, count: null });
    expect(await serviceDatabase().from('posts').select('id').eq('id', 999).maybeSingle()).toEqual({ data: null, error: null, count: null });
    expect((await serviceDatabase().from('posts').select('id').eq('id', 999).single()).error?.code).toBe('PGRST116');
    expect((await serviceDatabase().from('posts').select('id').maybeSingle()).error?.code).toBe('PGRST116');
  });

  it('inserts JSONB and bulk defaults, and normalizes database timestamps to ISO strings', async () => {
    const sources = [{ label: 'A source', url: 'https://example.test/?quote="' }];
    const result = await serviceDatabase().from('posts').insert([
      { title: 'JSON story', sources, score: 50 },
      { title: 'Default story', note: undefined },
    ]).select('title,score,sources,created_at').order('id');
    expect(result.error?.code).toBe('INVALID_QUERY');
    const inserted = await serviceDatabase().from('posts').insert([
      { title: 'JSON story', sources, score: 50 }, { title: 'Default story', note: undefined },
    ]).select('title,score,sources,created_at');
    expect(inserted.error).toBeNull();
    expect(inserted.data).toEqual([
      { title: 'JSON story', score: 50, sources, created_at: '2026-10-12T12:00:00.000Z' },
      { title: 'Default story', score: 0, sources: [], created_at: '2026-10-12T12:00:00.000Z' },
    ]);
  });

  it('keeps mutations private by default and safely scopes updates and deletes', async () => {
    expect(await serviceDatabase().from('posts').insert({ title: 'New draft' })).toEqual({ data: null, error: null, count: null });
    const changed = await serviceDatabase().from('posts').update({ note: 'Edited' }).eq('id', 1).is('note', null).select('id,note', { count: 'exact' });
    expect(changed).toEqual({ data: [{ id: 1, note: 'Edited' }], error: null, count: 1 });
    const removed = await serviceDatabase().from('posts').delete().eq('title', 'New draft').select('title').single();
    expect(removed.data).toEqual({ title: 'New draft' });
    expect((await serviceDatabase().from('posts').select('id', { count: 'exact' })).count).toBe(4);
  });

  it('upserts only supplied fields and honors conflict targets and ignored duplicates', async () => {
    const edited = await serviceDatabase().from('posts').upsert({ title: 'Published one', score: 99 }, { onConflict: 'title' }).select('id,score,is_published').single();
    expect(edited.data).toEqual({ id: 1, score: 99, is_published: true });
    const ignored = await serviceDatabase().from('posts').upsert({ title: 'Published one', score: 0 }, { onConflict: 'title', ignoreDuplicates: true }).select('id');
    expect(ignored.data).toEqual([]);
    expect((await serviceDatabase().from('posts').select('score').eq('id', 1).single()).data).toEqual({ score: 99 });
    const onlyKey = await serviceDatabase().from('posts').upsert({ title: 'Published one' }, { onConflict: 'title' }).select('id');
    expect(onlyKey.error).toBeNull();
    expect(onlyKey.data).toEqual([]);
  });

  it('executes a thenable mutation once even when multiple callers await it', async () => {
    const mutation = serviceDatabase().from('posts').insert({ title: 'One execution' }).select('id');
    const [first, second] = await Promise.all([mutation, mutation]);
    expect(first.error).toBeNull();
    expect(second).toEqual(first);
    expect(statements).toHaveLength(1);
  });

  it('binds named RPC arguments and preserves JSON and scalar results', async () => {
    const payload = { nested: ['value', { key: "'); DROP TABLE posts; --" }] };
    const result = await serviceDatabase().rpc('echo_arguments', { p_payload: payload, p_text: 'Quoted \' text' });
    expect(result).toEqual({ data: { text: 'Quoted \' text', payload }, error: null, count: null });
    expect(statements[0].text).toBe('SELECT "public"."echo_arguments"("p_payload" => $1, "p_text" => $2) AS "result"');
    expect(await serviceDatabase().rpc('echo_boolean', { p_value: false })).toEqual({ data: false, error: null, count: null });
  });

  it('preserves safe SQLSTATE codes while redacting failing rows and connection details', async () => {
    const duplicate = await serviceDatabase().from('posts').insert({ title: 'Published one', author_email: 'secret@illinois.edu' });
    expect(duplicate.error?.code).toBe('23505');
    expect(JSON.stringify(duplicate)).not.toMatch(/Published one|secret@illinois.edu/);
  });
});

describe('SQL validation and anonymous database isolation', () => {
  it('rejects unsafe identifiers, projections and conflict clauses before transport', async () => {
    const client = serviceDatabase();
    const attacks = [
      client.from('posts; DROP TABLE posts'),
      client.from('public.posts'),
      client.from('posts').select('id, (select author_email from posts)'),
      client.from('posts').select('id:author_email'),
      client.from('posts').select('posts(*)'),
      client.from('posts').select('id,,title'),
      client.from('posts').eq('id) OR true --', 1),
      client.from('posts').order('id DESC; DROP TABLE posts'),
      client.from('posts').insert({ 'title) VALUES (1); --': 'attack' }),
      client.from('posts').upsert({ title: 'attack' }, { onConflict: 'title) DO UPDATE SET score=0; --' }),
    ];
    for (const result of await Promise.all(attacks)) expect(result.error?.code).toBe('INVALID_QUERY');
    expect((await client.rpc('echo_boolean; DELETE FROM posts', { p_value: true })).error?.code).toBe('INVALID_QUERY');
    expect((await client.rpc('echo_boolean', { 'p_value) => true); --': true })).error?.code).toBe('INVALID_QUERY');
    expect(statements).toHaveLength(0);
  });

  it('rejects invalid pagination, values and empty writes without executing SQL', async () => {
    const client = serviceDatabase();
    const invalid = [
      client.from('posts').limit(-1), client.from('posts').limit(Number.NaN),
      client.from('posts').range(4, 3), client.from('posts').range(0.5, 1),
      client.from('posts').eq('id', undefined), client.from('posts').eq('id', () => 'attack'),
      client.from('posts').insert([]), client.from('posts').insert(null), client.from('posts').update({}),
    ];
    for (const result of await Promise.all(invalid)) expect(result.error?.code).toBe('INVALID_QUERY');
    expect(statements).toHaveLength(0);
  });

  it('reads published views as anon in one read-only transaction and restores owner privilege afterward', async () => {
    const result = await publicDatabase()!.from('public_posts').select('id,title', { count: 'exact' }).order('id');
    expect(result.error).toBeNull();
    expect(result.data?.map(row => row.id)).toEqual([1, 3, 4]);
    expect(result.count).toBe(3);
    expect(transactions).toHaveLength(1);
    expect(transactions[0]).toMatchObject({ readOnly: true, fetchOptions: { cache: 'no-store' } });
    expect(statements[0]).toEqual({ text: 'SET LOCAL ROLE anon', values: [], transaction: true });
    expect(statements.every(statement => statement.transaction)).toBe(true);
    const privateRows = await serviceDatabase().from('posts').select('id,author_email');
    expect(privateRows.data).toHaveLength(4);
    expect(privateRows.data?.[0].author_email).toBe('private@illinois.edu');
    expect(statements.at(-1)?.transaction).toBe(false);
  });

  it('blocks private tables, unapproved public-prefixed views, every mutation and every RPC', async () => {
    const client = publicDatabase()!;
    for (const query of [
      client.from('posts').select('author_email'),
      client.from('public_unapproved').select('author_email'),
      client.from('public_posts').insert({ title: 'attack' }),
      client.from('public_posts').upsert({ title: 'attack' }),
      client.from('public_posts').update({ title: 'attack' }),
      client.from('public_posts').delete(),
    ]) expect((await query).error?.code).toBe('42501');
    expect((await client.rpc('echo_boolean', { p_value: true })).error?.code).toBe('42501');
    expect(statements).toHaveLength(0);
  });

  it('fails closed on database privilege errors without falling back to owner queries', async () => {
    await db.exec('REVOKE SELECT ON public_posts FROM anon');
    try {
      const result = await publicDatabase()!.from('public_posts').select('id');
      expect(result.error?.code).toBe('42501');
      expect(result.data).toBeNull();
      expect(statements.every(statement => statement.transaction)).toBe(true);
      expect(transactions).toHaveLength(1);
      expect((await serviceDatabase().from('posts').select('id')).data).toHaveLength(4);
    } finally { await db.exec('GRANT SELECT ON public_posts TO anon'); }
  });

  it('rechecks publication state on each public query so withdrawn covers cannot retain access', async () => {
    const client = publicDatabase()!;
    expect((await client.from('public_posts').select('id').eq('id', 1).maybeSingle()).data).toEqual({ id: 1 });
    expect((await serviceDatabase().from('posts').update({ is_published: false }).eq('id', 1)).error).toBeNull();
    expect((await client.from('public_posts').select('id').eq('id', 1).maybeSingle()).data).toBeNull();
    expect(transactions).toHaveLength(2);
  });

  it('uses only server DATABASE_URL and no-store transport for both client modes', () => {
    publicDatabase();
    serviceDatabase();
    for (const call of mocks.neon.mock.calls) expect(call).toEqual([
      'postgresql://test:secret@test.neon.tech/test', { fullResults: true, fetchOptions: { cache: 'no-store' } },
    ]);
    vi.stubEnv('DATABASE_URL', '');
    expect(publicDatabase()).toBeNull();
    expect(() => serviceDatabase()).toThrow('not connected');
  });

  it('redacts driver initialization failures that can contain the connection password', () => {
    mocks.neon.mockImplementationOnce(() => { throw new Error('Invalid postgres://test:private-password@host/database'); });
    expect(() => serviceDatabase()).toThrow('The database connection could not be initialized.');
  });

  it('keeps separately constructed service and anonymous clients isolated', async () => {
    const publicClient = createDatabase('postgresql://test:secret@test.neon.tech/test', 'public');
    const serviceClient = createDatabase('postgresql://test:secret@test.neon.tech/test', 'service');
    expect((await publicClient.from('posts')).error?.code).toBe('42501');
    expect((await serviceClient.from('posts').select('id')).data).toHaveLength(4);
    expect((await publicClient.from('public_posts').select('id')).data).toHaveLength(3);
  });
});
